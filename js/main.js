let currentLang = localStorage.getItem('lang') || 'fr';

function setLanguage(lang){
  currentLang = lang;
  localStorage.setItem('lang', lang);
  const d = T[lang];
  const isAr = lang === 'ar';
  // Update html attributes
  document.documentElement.lang = lang;
  document.documentElement.dir = isAr ? 'rtl' : 'ltr';
  // Update all text nodes
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const k = el.getAttribute('data-i18n');
    if(d[k] !== undefined) el.textContent = d[k];
  });
  // Update all innerHTML nodes
  document.querySelectorAll('[data-i18n-html]').forEach(el=>{
    const k = el.getAttribute('data-i18n-html');
    if(d[k] !== undefined) el.innerHTML = d[k];
  });
  // Update about body (complex HTML)
  const ab = document.getElementById('aboutBody');
  if(ab && d['about.body']) ab.innerHTML = d['about.body'];
  // Hero name: Arabic = سعد زيلالي (first name first), others = Zilali / Saad
  const heroName = document.getElementById('heroName');
  if(heroName){
    if(isAr) heroName.innerHTML = 'سعد<br><em>زيلالي</em>';
    else heroName.innerHTML = 'Zilali<br><em>Saad</em>';
  }
  // Nav brand name
  const navBrand = document.getElementById('navBrand');
  if(navBrand){
    const dot = '<span style="color:rgba(255,255,255,0.35);margin:0 0.35rem">·</span>';
    if(isAr) navBrand.innerHTML = 'سعد' + dot + 'زيلالي';
    else navBrand.innerHTML = 'Zilali' + dot + 'Saad';
  }
  // Hide Arabic subtitle line in hero thesis box when not Arabic (it's always visible as decoration in FR/EN)
  const thesisAr = document.querySelector('.hero-thesis-ar');
  if(thesisAr) thesisAr.style.display = isAr ? 'none' : 'block';
  // Hide Arabic pub titles when not Arabic
  document.querySelectorAll('.pub-title-ar').forEach(el => el.style.display = isAr ? 'none' : 'block');
  // Update lang buttons
  document.querySelectorAll('.lang-btn').forEach(btn=>{
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });
  // Title
  const titles = {fr:'Zilali Saad — Doctorant en Droit | Droits de l\'Homme',en:'Saad Zilali — PhD Candidate in Law | Human Rights',ar:'سعد زيلالي — طالب دكتوراه في القانون | حقوق الإنسان'};
  document.title = titles[lang];
}

